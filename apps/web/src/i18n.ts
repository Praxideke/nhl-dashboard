export type Translation = typeof T['en']

export function translateConf(conf: string, t: Translation): string {
  if (conf === 'Eastern') return t.confEastern
  if (conf === 'Western') return t.confWestern
  return conf
}

export function translateDiv(div: string, t: Translation): string {
  switch (div) {
    case 'Atlantic': return t.divAtlantic
    case 'Metropolitan': return t.divMetropolitan
    case 'Central': return t.divCentral
    case 'Pacific': return t.divPacific
    default: return div
  }
}
